"""Command line tools: `python -m app.cli --help`."""

import argparse
import json
import sys
import time
from pathlib import Path

from app import repo
from app.config import get_settings
from app.db import init_db, session
from app.security import sanitize_theme
from app.seed import seed_demo_data
from app.services import pipeline


def cmd_seed(_args) -> None:
    settings = get_settings()
    init_db(settings.db_path)
    with session(settings.db_path) as conn:
        print("Seeded Sunbeam Theatre." if seed_demo_data(conn) else "Archive is not empty; nothing to do.")


def cmd_refresh(args) -> None:
    settings = get_settings()
    init_db(settings.db_path)
    with session(settings.db_path) as conn:
        sites = [repo.get_site_by_slug(conn, args.slug)] if args.slug else repo.list_sites(conn, published_only=False)
    for site in sites:
        if not site:
            sys.exit(f"Unknown site: {args.slug}")
        print(f"== {site['title']} ({site['slug']})")
        for name in args.what:
            fn = {"photos": pipeline.refresh_photos, "models": pipeline.find_models, "news": pipeline.check_news}[name]
            try:
                print(f"  {name}: {fn(settings, site['id'])}")
            except Exception as exc:  # noqa: BLE001
                print(f"  {name}: failed: {exc}")
            if name == "news" and settings.news_provider == "gdelt":
                time.sleep(6)


def cmd_import_legacy(args) -> None:
    """Import sites generated by the first prototype (archive_data.json)."""
    settings = get_settings()
    init_db(settings.db_path)
    legacy = json.loads(Path(args.path).read_text(encoding="utf-8"))
    imported = 0
    with session(settings.db_path) as conn:
        for key, entry in legacy.items():
            data = entry.get("full_data")
            if entry.get("is_custom") or not data:
                continue
            slug = pipeline.unique_slug(conn, data.get("title") or key, None)
            cameras = pipeline.DEFAULT_TOUR_CAMERAS
            content = {
                "tour_cards": [{"title": c["title"], "content": c["content"], "source_refs": [],
                                "camera": cameras[i % len(cameras)].model_dump()}
                               for i, c in enumerate(data.get("about_cards", []))],
                "culture_title": data.get("culture_title", ""), "culture_subtitle": data.get("culture_subtitle", ""),
                "culture_cards": [{"title": c["title"], "content": c["content"], "source_refs": []}
                                  for c in data.get("culture_cards", [])],
                "quick_facts": [{"text": f, "source_refs": []} for f in data.get("quick_facts", [])],
                "did_you_know": {"text": data.get("did_you_know_text", ""), "source_refs": []},
            }
            lat, lon = data.get("latitude") or None, data.get("longitude") or None
            repo.insert_site(conn, {
                "slug": slug, "title": data.get("title", key), "native_name": data.get("subtitle", ""),
                "location_label": data.get("label", ""), "tagline": data.get("tagline", ""),
                "latitude": lat, "longitude": lon, "coord_source": "ai" if lat else "none",
                "content": content, "theme": sanitize_theme(data.get("theme")), "generation_mode": "legacy",
            })
            imported += 1
            print(f"Imported {data.get('title')} -> /site/{slug}")
    print(f"{imported} site(s) imported. Legacy records have no sources: regenerate them from the admin area.")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="python -m app.cli", description="SAVE Heritage maintenance commands")
    sub = parser.add_subparsers(required=True)

    sub.add_parser("seed", help="Insert the Sunbeam Theatre demo record into an empty archive").set_defaults(fn=cmd_seed)

    refresh = sub.add_parser("refresh", help="Fetch archive photos and news for one or all sites")
    refresh.add_argument("slug", nargs="?", help="Site slug; all sites if omitted")
    refresh.add_argument("--what", nargs="+", choices=["photos", "news"], default=["photos", "news"])
    refresh.set_defaults(fn=cmd_refresh)

    legacy = sub.add_parser("import-legacy", help="Import archive_data.json from the first prototype")
    legacy.add_argument("path")
    legacy.set_defaults(fn=cmd_import_legacy)

    args = parser.parse_args(argv)
    args.fn(args)


if __name__ == "__main__":
    main()
